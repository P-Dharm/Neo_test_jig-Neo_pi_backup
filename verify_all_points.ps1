$case2_data = @(
    # 5.0V Points
    @{ V=5.0; R="690";  I_des=7.1429; V_adc=1500.95 },
    @{ V=5.0; R="910";  I_des=5.4348; V_adc=1185.22 },
    @{ V=5.0; R="1000"; I_des=4.9505; V_adc=1089.36 },
    @{ V=5.0; R="3300"; I_des=1.5106; V_adc= 396.68 },
    @{ V=5.0; R="3881"; I_des=1.2850; V_adc= 356.60 },
    @{ V=5.0; R="5100"; I_des=0.9785; V_adc= 335.26 },

    # 3.6V Points
    @{ V=3.6; R="470";  I_des=7.5000; V_adc=1589.60 },
    @{ V=3.6; R="503";  I_des=7.0175; V_adc=1455.90 },
    @{ V=3.6; R="570";  I_des=6.2069; V_adc=1331.70 },
    @{ V=3.6; R="590";  I_des=6.0000; V_adc=1291.80 },
    @{ V=3.6; R="690";  I_des=5.1429; V_adc=1122.50 },
    @{ V=3.6; R="910";  I_des=3.9130; V_adc= 876.80 },
    @{ V=3.6; R="1000"; I_des=3.5644; V_adc= 811.20 }
)

$gain = 18.6428
$rs = 10.0
$sens = $gain * $rs

Write-Output "========================================================================================="
Write-Output ("{0,-5} | {1,-5} | {2,-7} | {3,-7} | {4,-15} | {5,-15} | {6,-15}" -f "Volt", "Res", "I_des", "V_adc", "Off=117.78 Err", "Off=152.50 Err", "Dynamic Err")
Write-Output "========================================================================================="

foreach ($p in $case2_data) {
    $v = $p.V_adc
    
    # 1. Static 117.78
    $i_117 = ($v - 117.78) / $sens
    $err_117 = [Math]::Abs($i_117 - $p.I_des) / $p.I_des * 100.0
    
    # 2. Static 152.50
    $i_152 = ($v - 152.50) / $sens
    $err_152 = [Math]::Abs($i_152 - $p.I_des) / $p.I_des * 100.0
    
    # 3. Dynamic
    if ($v -ge 355.0) {
        $off_dyn = 117.78
    } elseif ($v -le 340.0) {
        $off_dyn = 152.50
    } else {
        $t = ($v - 340.0) / (355.0 - 340.0)
        $off_dyn = 152.50 - $t * (152.50 - 117.78)
    }
    $i_dyn = ($v - $off_dyn) / $sens
    $err_dyn = [Math]::Abs($i_dyn - $p.I_des) / $p.I_des * 100.0

    Write-Output ("{0,4}V | {1,5} | {2,7:F4} | {3,7:F2} | {4,7:F4} ({5,4:F1}%) | {6,7:F4} ({7,4:F1}%) | {8,7:F4} ({9,4:F1}%)" -f `
        $p.V, $p.R, $p.I_des, $p.V_adc, $i_117, $err_117, $i_152, $err_152, $i_dyn, $err_dyn)
}
